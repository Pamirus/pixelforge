#pragma once

#include "pixelforge/image.hpp"

#include <ostream>
#include <utility>

namespace pixelforge {

// How many times CountedImage objects were copied and moved since the last
// reset_counts().
struct CopyMoveCounts {
    int copy_constructions = 0;
    int copy_assignments = 0;
    int move_constructions = 0;
    int move_assignments = 0;

    int copies() const noexcept { return copy_constructions + copy_assignments; }
    int moves() const noexcept { return move_constructions + move_assignments; }

    friend bool operator==(const CopyMoveCounts&, const CopyMoveCounts&) = default;

    friend std::ostream& operator<<(std::ostream& out, const CopyMoveCounts& counts)
    {
        return out << "copy constructions " << counts.copy_constructions << ", copy assignments "
                   << counts.copy_assignments << ", move constructions "
                   << counts.move_constructions << ", move assignments "
                   << counts.move_assignments;
    }
};

// An Image that counts how often it is copied and moved, so tests and
// benchmarks can see which copies really happen. The counts are shared by all
// CountedImage objects and are not thread-safe.
class CountedImage {
public:
    CountedImage() = default;
    CountedImage(int width, int height) : image_(width, height) {}
    explicit CountedImage(Image image) noexcept : image_(std::move(image)) {}

    Image& image() noexcept { return image_; }
    const Image& image() const noexcept { return image_; }

    static CopyMoveCounts counts() noexcept { return counts_; }
    static void reset_counts() noexcept { counts_ = {}; }

private:
    // Counter's copy and move operations do the counting. CountedImage's own
    // copy and move are generated by the compiler and copy or move each
    // member, so they run Counter's and are counted too. That keeps
    // CountedImage at the Rule of Zero: only Counter writes the special
    // member functions, because counting is the one thing it does.
    struct Counter {
        Counter() = default;
        Counter(const Counter&) noexcept { ++counts_.copy_constructions; }
        Counter(Counter&&) noexcept { ++counts_.move_constructions; }
        Counter& operator=(const Counter&) noexcept
        {
            ++counts_.copy_assignments;
            return *this;
        }
        Counter& operator=(Counter&&) noexcept
        {
            ++counts_.move_assignments;
            return *this;
        }
        ~Counter() = default;
    };

    inline static CopyMoveCounts counts_{};

    // image_ comes first, so if copying its pixels throws, nothing is counted.
    Image image_;
    Counter counter_;
};

} // namespace pixelforge
